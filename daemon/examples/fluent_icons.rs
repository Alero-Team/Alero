fn main() {
    let pkg = std::env::args().nth(1).expect("path to the fluentui_system_icons package");
    let dart = fs::read_to_string(format!("{pkg}/lib/src/fluent_icons.dart")).expect("fluent_icons.dart");
    // `static const IconData wifi_1_24_regular = IconData(61697, ...`
    let codes: HashMap<&str, u32> = dart
        .lines()
        .filter_map(|l| {
            let l = l.trim().strip_prefix("static const IconData ")?;
            let (name, rest) = l.split_once(" = IconData(")?;
            Some((name, rest.split(',').next()?.trim().parse().ok()?))
        })
        .collect();
    let fonts: Vec<Vec<u8>> = ["Regular", "Filled"].iter().map(|f| fs::read(format!("{pkg}/lib/fonts/FluentSystemIcons-{f}.ttf")).expect("font")).collect();
    let ops = |name: &str, filled: bool| -> Vec<f32> {
        let key = format!("{name}_24_{}", if filled { "filled" } else { "regular" });
        let code = *codes.get(key.as_str()).unwrap_or_else(|| panic!("no {key}"));
        glyph_ops(&FontRef::try_from_slice(&fonts[filled as usize]).expect("ttf"), code)
    };
    let mut out = String::from(
        "// Generated by `cargo run --example fluent_icons`; do not edit. Fluent UI System Icons, MIT, (c) Microsoft.\n\
         // Each icon is a list of ops on the 24 × 24 grid: 0 move x y, 1 line x y, 2 quad x1 y1 x y, 3 cubic x1 y1 x2 y2 x y, 4 close.\n\n",
    );
    for filled in [false, true] {
        for (konst, name) in ICONS {
            let nums: Vec<String> = ops(name, filled).iter().map(|v| num(*v)).map(|s| if s.contains('.') { s } else { s + "." }).collect();
            writeln!(out, "pub const {konst}_{}: &[f32] = &[{}];", if filled { "FILLED" } else { "REGULAR" }, nums.join(",")).unwrap();
        }
    }
    fs::write("src/island/fluent.rs", out).expect("write");
    for (file, name, filled, colour) in DRAWABLES {
        let o = ops(name, *filled);
        let mut d = String::new();
        let mut i = 0;
        while i < o.len() {
            let (cmd, n) = match o[i] as u8 { 0 => ('M', 2), 1 => ('L', 2), 2 => ('Q', 4), 3 => ('C', 6), _ => ('Z', 0) };
            d.push(cmd);
            d.push_str(&o[i + 1..i + 1 + n].iter().map(|v| num(*v)).collect::<Vec<_>>().join(","));
            i += 1 + n;
        }
        let xml = format!(
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Fluent UI System Icons ({name}, MIT, Microsoft). Generated by daemon/examples/fluent_icons.rs. -->\n\
             <vector xmlns:android=\"http://schemas.android.com/apk/res/android\" android:width=\"24dp\" android:height=\"24dp\" android:viewportWidth=\"24\" android:viewportHeight=\"24\">\n    \
             <path android:fillColor=\"{colour}\" android:pathData=\"{d}\" />\n</vector>\n"
        );
        fs::write(format!("../app/android/app/src/main/res/drawable/{file}.xml"), xml).expect("write drawable");
    }
}

fn num(v: f32) -> String {
    format!("{}", (v * 100.0).round() / 100.0)
}

/// The glyph's outline on the 24-grid (y down), as the ops described in the generated file's header.
fn glyph_ops(font: &FontRef, code: u32) -> Vec<f32> {
    let em = font.units_per_em().expect("units per em");
    let top = font.ascent_unscaled();
    let p = |p: Point| [p.x / em * 24.0, (top - p.y) / em * 24.0];
    let outline = font.outline(font.glyph_id(char::from_u32(code).unwrap())).expect("outline");
    let mut ops: Vec<f32> = Vec::new();
    let mut end: Option<Point> = None;
    for c in &outline.curves {
        let (start, last) = match c {
            OutlineCurve::Line(a, b) | OutlineCurve::Quad(a, _, b) | OutlineCurve::Cubic(a, _, _, b) => (*a, *b),
        };
        // A curve that does not start where the last one ended begins a new contour.
        if end.is_none_or(|e| (e.x - start.x).abs() > 0.01 || (e.y - start.y).abs() > 0.01) {
            if end.is_some() {
                ops.push(4.0);
            }
            ops.push(0.0);
            ops.extend(p(start));
        }
        match c {
            OutlineCurve::Line(_, b) => ops.extend([1.0].into_iter().chain(p(*b))),
            OutlineCurve::Quad(_, k, b) => ops.extend([2.0].into_iter().chain(p(*k)).chain(p(*b))),
            OutlineCurve::Cubic(_, k1, k2, b) => ops.extend([3.0].into_iter().chain(p(*k1)).chain(p(*k2)).chain(p(*b))),
        }
        end = Some(last);
    }
    ops.push(4.0);
    ops
}
